package Java_10_Strings;

public class string_09_Plus_in_string {
    static void main(String[] args) {
        String s="Subham";

        s=s+" Jha don hai";

        s=s+10;

        s+='k';

        s+='\n';

        s+='S';

        System.out.println(s);

        System.out.println("Golu"+10+20);

        System.out.println(10+"Golu"+20);

        System.out.println(10+20+"Golu");

        System.out.println('A'+"Golu");

        System.out.println('A'+2+"Golu");
    }
}
