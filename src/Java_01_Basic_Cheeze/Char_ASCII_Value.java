package Java_01_Basic_Cheeze;

public class Char_ASCII_Value {
    public static void main(String[] args){
        char ch = '0';
        int x =(int) ch;
        System.out.println(x);

        char Ch = 'A';
        int y = (int)Ch;
        System.out.println(y);

        char CH = 'a';
        System.out.println((int)CH);

        char cH = 'k';
        System.out.println(cH+0);

        int  p = 65;
        char q = (char)p;
        System.out.print((q));

    }
}
