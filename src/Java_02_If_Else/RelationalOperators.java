package Java_02_If_Else;

public class RelationalOperators {
    public static void main(String[] args){

        System.out.println(5 > 3);
        System.out.println(5 < 3);
        System.out.println(5 >= 3);
        System.out.println(5 <= 3);
        System.out.println(5 != 3);

        boolean x = (5>3);
        System.out.println(x);
    }
}
